-- =============================================================================
-- Cotizadora I.C.T. — esquema, seguridad a nivel de fila y almacenamiento
-- -----------------------------------------------------------------------------
-- Se corre una vez por proyecto de Supabase (una tienda = un proyecto).
-- Orden: 0001_esquema.sql → 0002_catalogo.sql → 0003_demo.sql
--
-- Reglas de seguridad:
-- - El público (rol anon) solo lee la tienda, los modelos activos, sus fichas y
--   los equipos publicados con stock mayor que 0 de modelos activos.
-- - Solo los usuarios con perfil activo (agencia o tienda) escriben.
-- - Aquí NO se guardan datos personales de clientes: van solo a GHL.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Tablas
-- -----------------------------------------------------------------------------

create table public.tienda (
  id                        smallint primary key default 1 check (id = 1),
  nombre                    text not null default '',
  ciudad                    text not null default '',
  direccion                 text not null default '',
  horario_texto             text not null default '',
  whatsapp                  text not null default ''
                              check (whatsapp = '' or whatsapp ~ '^57[0-9]{10}$'),
  correo_contacto           text not null default '',
  instagram_url             text not null default '',
  facebook_url              text not null default '',
  tiktok_url                text not null default '',
  logo                      text not null default '',   -- ruta en el bucket "marca"
  favicon                   text not null default '',   -- ruta en el bucket "marca"
  color_primario            text not null default '#1A73E8'
                              check (color_primario ~ '^#[0-9A-Fa-f]{6}$'),
  color_secundario          text not null default '#0F172A'
                              check (color_secundario ~ '^#[0-9A-Fa-f]{6}$'),
  tema                      text not null default 'claro' check (tema in ('claro', 'oscuro')),
  texto_entrega             text not null default '',
  formas_pago               text[] not null default '{}',
  texto_garantia_nuevos     text not null default '',
  texto_garantia_usados     text not null default '',
  etiqueta_precio           text not null default 'Precio',
  texto_privacidad          text not null default '',
  texto_terminos            text not null default '',
  texto_autorizacion_datos  text not null default '',
  aviso_marca               text not null default '',
  precios_actualizados_en   timestamptz,
  modo_demo                 boolean not null default true,
  actualizado_en            timestamptz not null default now()
);

create table public.modelos (
  id               bigint generated by default as identity primary key,
  nombre           text not null unique check (btrim(nombre) <> ''),
  slug             text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  generacion       text not null check (btrim(generacion) <> ''),
  orden            integer not null,
  activo           boolean not null default false,
  -- true si lo activaron los datos de demostración; "Borrar datos de
  -- demostración" lo vuelve a apagar. Se pone en false si alguien lo toca.
  activo_por_demo  boolean not null default false,
  creado_en        timestamptz not null default now()
);

create table public.fichas (
  modelo_id         bigint primary key references public.modelos (id) on delete cascade,
  descripcion       text not null default '',
  -- Lista ordenada de pares: [{"etiqueta": "Pantalla", "valor": "..."}]
  especificaciones  jsonb not null default '[]'::jsonb
                      check (jsonb_typeof(especificaciones) = 'array'),
  actualizado_en    timestamptz not null default now()
);

create table public.equipos (
  id                  uuid primary key default gen_random_uuid(),
  modelo_id           bigint not null references public.modelos (id) on delete restrict,
  condicion           text not null check (condicion in ('nuevo', 'usado')),
  capacidad           text not null check (btrim(capacidad) <> ''),
  color_nombre        text not null default '',
  color_hex           text not null default '#8E8E93' check (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
  precio              bigint not null check (precio > 0),
  stock               integer not null default 1 check (stock >= 0),
  fotos               text[] not null default '{}' check (cardinality(fotos) <= 6),  -- rutas en "fotos"
  publicado           boolean not null default false,
  destacado           boolean not null default false,
  descripcion_extra   text not null default '',
  es_demo             boolean not null default false,
  -- Solo usados
  bateria_porcentaje  smallint check (bateria_porcentaje between 0 and 100),
  estado_estetico     text check (estado_estetico in ('Como nuevo', 'Excelente', 'Muy bueno', 'Bueno')),
  detalles            text not null default '',
  incluye             text not null default '',
  creado_en           timestamptz not null default now(),
  actualizado_en      timestamptz not null default now(),
  -- Un usado es una unidad física: stock 1 (o 0 cuando se vendió).
  constraint usado_es_una_unidad check (condicion = 'nuevo' or stock <= 1)
);

create index equipos_modelo_idx on public.equipos (modelo_id);
create index equipos_publicos_idx on public.equipos (publicado, stock);

create table public.perfiles (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  correo     text not null,
  rol        text not null check (rol in ('agencia', 'tienda')),
  activo     boolean not null default true,
  creado_en  timestamptz not null default now()
);

-- La única fila de la tienda.
insert into public.tienda (id) values (1);

-- -----------------------------------------------------------------------------
-- Funciones de rol (security definer para poder leer perfiles desde las políticas)
-- -----------------------------------------------------------------------------

create or replace function public.rol_actual()
returns text
language sql stable security definer set search_path = public
as $$
  select rol from public.perfiles where user_id = auth.uid() and activo
$$;

create or replace function public.es_staff()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(public.rol_actual() is not null, false)
$$;

create or replace function public.es_agencia()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(public.rol_actual() = 'agencia', false)
$$;

-- -----------------------------------------------------------------------------
-- Disparadores
-- -----------------------------------------------------------------------------

create or replace function public.tocar_actualizado_en()
returns trigger language plpgsql as $$
begin
  new.actualizado_en := now();
  return new;
end $$;

create trigger tienda_actualizado before update on public.tienda
  for each row execute function public.tocar_actualizado_en();
create trigger fichas_actualizado before update on public.fichas
  for each row execute function public.tocar_actualizado_en();
create trigger equipos_actualizado before update on public.equipos
  for each row execute function public.tocar_actualizado_en();

-- "Precios actualizados al ...": cambia sola cuando se carga o cambia un precio.
create or replace function public.marcar_precios_actualizados()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.precio is distinct from old.precio then
    update public.tienda set precios_actualizados_en = now() where id = 1;
  end if;
  return null;
end $$;

create trigger equipos_precio after insert or update of precio on public.equipos
  for each row execute function public.marcar_precios_actualizados();

-- Cada modelo nuevo nace con su ficha vacía.
create or replace function public.crear_ficha_vacia()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.fichas (modelo_id) values (new.id) on conflict do nothing;
  return null;
end $$;

create trigger modelos_ficha after insert on public.modelos
  for each row execute function public.crear_ficha_vacia();

-- El rol "tienda" solo puede activar o desactivar modelos. Nombre, slug,
-- generación y orden los cambia la agencia. Sin sesión (SQL o service_role)
-- no se restringe.
create or replace function public.proteger_catalogo()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.es_agencia() and (
       new.nombre is distinct from old.nombre
    or new.slug is distinct from old.slug
    or new.generacion is distinct from old.generacion
    or new.orden is distinct from old.orden) then
    raise exception 'Solo la agencia puede cambiar el nombre, la generación o el orden del catálogo.'
      using errcode = '42501';
  end if;
  if auth.uid() is not null and new.activo is distinct from old.activo then
    new.activo_por_demo := false;
  end if;
  return new;
end $$;

create trigger modelos_proteger before update on public.modelos
  for each row execute function public.proteger_catalogo();

-- El modo demo solo lo cambia la agencia.
create or replace function public.proteger_tienda()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.es_agencia()
     and new.modo_demo is distinct from old.modo_demo then
    raise exception 'Solo la agencia puede cambiar el modo demo.' using errcode = '42501';
  end if;
  return new;
end $$;

create trigger tienda_proteger before update on public.tienda
  for each row execute function public.proteger_tienda();

-- Un usuario no se puede quitar a sí mismo el rol de agencia ni desactivarse.
create or replace function public.proteger_perfil()
returns trigger language plpgsql as $$
begin
  if auth.uid() is not null and old.user_id = auth.uid()
     and (new.rol is distinct from old.rol or new.activo is distinct from old.activo) then
    raise exception 'No puede cambiar su propio rol ni desactivarse.' using errcode = '42501';
  end if;
  return new;
end $$;

create trigger perfiles_proteger before update on public.perfiles
  for each row execute function public.proteger_perfil();

-- -----------------------------------------------------------------------------
-- Seguridad a nivel de fila
-- -----------------------------------------------------------------------------

alter table public.tienda   enable row level security;
alter table public.modelos  enable row level security;
alter table public.fichas   enable row level security;
alter table public.equipos  enable row level security;
alter table public.perfiles enable row level security;

-- Permisos de tabla: el público solo lee; los usuarios con sesión escriben
-- (siempre filtrados por las políticas de abajo).
revoke all on public.tienda, public.modelos, public.fichas, public.equipos, public.perfiles from anon, authenticated;
grant select on public.tienda, public.modelos, public.fichas, public.equipos to anon, authenticated;
grant update on public.tienda to authenticated;
grant insert, update, delete on public.modelos, public.fichas, public.equipos to authenticated;
grant select, update on public.perfiles to authenticated;

-- tienda
create policy tienda_leer on public.tienda for select to anon, authenticated using (true);
create policy tienda_editar on public.tienda for update to authenticated
  using (public.es_staff()) with check (public.es_staff());

-- modelos
create policy modelos_leer on public.modelos for select to anon, authenticated
  using (activo or public.es_staff());
create policy modelos_editar on public.modelos for update to authenticated
  using (public.es_staff()) with check (public.es_staff());
create policy modelos_agregar on public.modelos for insert to authenticated
  with check (public.es_agencia());
create policy modelos_borrar on public.modelos for delete to authenticated
  using (public.es_agencia());

-- fichas
create policy fichas_leer on public.fichas for select to anon, authenticated
  using (public.es_staff() or exists (
    select 1 from public.modelos m where m.id = fichas.modelo_id and m.activo));
create policy fichas_agregar on public.fichas for insert to authenticated
  with check (public.es_staff());
create policy fichas_editar on public.fichas for update to authenticated
  using (public.es_staff()) with check (public.es_staff());
create policy fichas_borrar on public.fichas for delete to authenticated
  using (public.es_staff());

-- equipos
create policy equipos_leer on public.equipos for select to anon, authenticated
  using (public.es_staff() or (publicado and stock > 0 and exists (
    select 1 from public.modelos m where m.id = equipos.modelo_id and m.activo)));
create policy equipos_agregar on public.equipos for insert to authenticated
  with check (public.es_staff());
create policy equipos_editar on public.equipos for update to authenticated
  using (public.es_staff()) with check (public.es_staff());
create policy equipos_borrar on public.equipos for delete to authenticated
  using (public.es_staff());

-- perfiles: cada uno ve el suyo; la agencia ve y edita todos.
-- Invitar usuarios se hace con la función "usuarios" (necesita la clave de servicio).
create policy perfiles_leer on public.perfiles for select to authenticated
  using (user_id = auth.uid() or public.es_agencia());
create policy perfiles_editar on public.perfiles for update to authenticated
  using (public.es_agencia()) with check (public.es_agencia());

-- -----------------------------------------------------------------------------
-- Lectura pública en una sola llamada (respeta la seguridad de arriba)
-- -----------------------------------------------------------------------------

create or replace function public.datos_publicos()
returns jsonb
language sql stable security invoker set search_path = public
as $$
  select jsonb_build_object(
    'tienda',  (select to_jsonb(t) from public.tienda t where id = 1),
    'modelos', coalesce((select jsonb_agg(to_jsonb(m) order by m.orden) from public.modelos m where m.activo), '[]'::jsonb),
    'fichas',  coalesce((select jsonb_agg(to_jsonb(f)) from public.fichas f
                          join public.modelos m on m.id = f.modelo_id and m.activo), '[]'::jsonb),
    'equipos', coalesce((select jsonb_agg(to_jsonb(e)) from public.equipos e
                          join public.modelos m on m.id = e.modelo_id and m.activo
                          where e.publicado and e.stock > 0), '[]'::jsonb)
  )
$$;

grant execute on function public.datos_publicos() to anon, authenticated;

-- -----------------------------------------------------------------------------
-- Borrar datos de demostración (solo agencia)
-- -----------------------------------------------------------------------------

create or replace function public.borrar_datos_demo()
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.es_agencia() then
    raise exception 'Solo la agencia puede borrar los datos de demostración.' using errcode = '42501';
  end if;
  delete from public.equipos where es_demo;
  update public.modelos set activo = false, activo_por_demo = false where activo_por_demo;
  update public.tienda set modo_demo = false where id = 1;
end $$;

revoke execute on function public.borrar_datos_demo() from public, anon;
grant execute on function public.borrar_datos_demo() to authenticated;

