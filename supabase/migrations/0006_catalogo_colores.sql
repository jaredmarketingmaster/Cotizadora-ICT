-- Reglas para los usuarios del panel (sin sesión, SQL o service_role, no se
-- restringe):
-- - Un color oficial no cambia de nombre, modelo ni orden, y no se borra.
-- - El hexadecimal de la fuente no cambia; el que falta se puede completar.
-- - Los colores de la tienda solo se agregan a modelos sin colores oficiales.
create or replace function public.proteger_color()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  if tg_op = 'INSERT' then
    if new.oficial or new.hex_de_fuente then
      raise exception 'Los colores oficiales vienen de la fuente: no se pueden crear desde el panel.' using errcode = '42501';
    end if;
    if exists (select 1 from public.colores c where c.modelo_id = new.modelo_id and c.oficial) then
      raise exception 'Este modelo tiene colores oficiales: no se le pueden agregar otros.' using errcode = '42501';
    end if;
    return new;
  end if;
  if tg_op = 'DELETE' then
    -- Al borrar el modelo (agencia), sus colores se van en cascada.
    if old.oficial and exists (select 1 from public.modelos m where m.id = old.modelo_id) then
      raise exception 'Un color oficial no se puede borrar.' using errcode = '42501';
    end if;
    return old;
  end if;
  if new.modelo_id is distinct from old.modelo_id or new.oficial is distinct from old.oficial
     or new.hex_de_fuente is distinct from old.hex_de_fuente
     or (old.oficial and (new.nombre_es is distinct from old.nombre_es
                          or new.nombre_en is distinct from old.nombre_en
                          or new.orden is distinct from old.orden)) then
    raise exception 'El nombre de un color oficial no se puede cambiar.' using errcode = '42501';
  end if;
  if old.hex_de_fuente and new.hex is distinct from old.hex then
    raise exception 'El hexadecimal de este color viene de la fuente y no se puede cambiar.' using errcode = '42501';
  end if;
  return new;
end $$;

create trigger colores_proteger before insert or update or delete on public.colores
  for each row execute function public.proteger_color();

-- Seguridad: el público lee solo los colores de modelos activos; la escritura
-- sigue los permisos del catálogo (todos completan; la agencia agrega y borra).
alter table public.colores enable row level security;
revoke all on public.colores from anon, authenticated;
grant select on public.colores to anon, authenticated;
grant insert, update, delete on public.colores to authenticated;

create policy colores_leer on public.colores for select to anon, authenticated
  using (public.es_staff() or exists (
    select 1 from public.modelos m where m.id = colores.modelo_id and m.activo));
create policy colores_editar on public.colores for update to authenticated
  using (public.es_staff()) with check (public.es_staff());
create policy colores_agregar on public.colores for insert to authenticated
  with check (public.es_agencia());
create policy colores_borrar on public.colores for delete to authenticated
  using (public.es_agencia());

-- datos_publicos() suma los colores de los modelos activos.
create or replace function public.datos_publicos()
returns jsonb
language sql stable security invoker set search_path = public
as $$
  select jsonb_build_object(
    'tienda',  (select to_jsonb(t) from public.tienda t where id = 1),
    'modelos', coalesce((select jsonb_agg(to_jsonb(m) order by m.orden) from public.modelos m where m.activo), '[]'::jsonb),
    'fichas',  coalesce((select jsonb_agg(to_jsonb(f)) from public.fichas f
                          join public.modelos m on m.id = f.modelo_id and m.activo), '[]'::jsonb),
    'colores', coalesce((select jsonb_agg(to_jsonb(c) order by c.modelo_id, c.orden) from public.colores c
                          join public.modelos m on m.id = c.modelo_id and m.activo), '[]'::jsonb),
    'equipos', coalesce((select jsonb_agg(to_jsonb(e)) from public.equipos e
                          join public.modelos m on m.id = e.modelo_id and m.activo
                          where e.publicado and e.en_stock), '[]'::jsonb)
  )
$$;
